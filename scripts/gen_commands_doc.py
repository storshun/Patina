#!/usr/bin/env python3
"""Regenerates docs/COMMANDS.md from a running Patina (`patina --headless --port N`).

    ./build/patina --headless --port 7999 &   python3 scripts/gen_commands_doc.py 7999
"""
import json
import os
import socket
import sys

port = int(sys.argv[1]) if len(sys.argv) > 1 else 7860
s = socket.create_connection(("127.0.0.1", port), timeout=30)
s.sendall(b'{"id":1,"cmd":"list_commands","args":{}}\n')
buf = b""
while b"\n" not in buf:
    buf += s.recv(1 << 20)
cmds = json.loads(buf.split(b"\n", 1)[0])["result"]
hidden = {"list_commands", "bridge_open_mesh", "bridge_update_mesh", "bridge_export", "__stop_server"}
groups = [
    ("Project & files", ["ping", "get_state", "get_log", "open_file", "open_mesh", "new_project", "save_project",
                         "save_incremental", "set_resolution", "texture_tiles", "export_textures", "export_again", "reload_mesh",
                         "import_model_textures"]),
    ("Materials", ["list_materials", "get_material", "create_material", "import_material_folder",
                   "import_image_material", "set_paint_material", "export_material_maps"]),
    ("Brushes & tools", ["list_brushes", "set_brush", "save_brush_preset", "set_tool", "set_paint_channels",
                         "set_symmetry", "set_clone_source"]),
    ("Painting", ["paint_stroke", "paint_world_points", "fill", "pick"]),
    ("Stencils & text", ["set_stencil", "project_stencil", "list_fonts"]),
    ("Notes & compare view", ["add_note", "list_notes", "update_note", "delete_note", "go_to_note", "set_compare"]),
    ("Undo & history", ["undo", "redo", "history", "history_jump"]),
    ("Layers", ["list_layers", "add_layer", "remove_layer", "select_layer", "update_layer", "move_layer",
                "move_layer_into", "group_into_folder", "duplicate_layer", "solo_layer", "copy_layer_settings",
                "clear_layer", "set_layer_mask", "add_mask_effect", "add_instance", "make_independent"]),
    ("Smart materials", ["list_smart_materials", "apply_smart_material", "save_smart_material"]),
    ("Camera, view & images", ["set_camera", "set_viewport_size", "set_view", "set_environment", "render_view",
                               "render_image", "screenshot_window", "render_uv", "get_texture", "texture_check"]),
    ("Bakes", ["bake_mesh_maps", "bake_from_high_poly", "baked_maps"]),
    ("UVs", ["uv_make_island", "uv_density", "uv_orient", "uv_fix_overlaps", "uv_unwrap", "uv_pack", "uv_rectify", "uv_mirror", "uv_pin", "uv_restack", "uv_unstack", "uv_islands", "uv_transform",
             "uv_seams", "uv_info", "select_faces", "island_brush", "pick_face"]),
    ("Blender", ["send_to_blender", "send_model_to_blender", "blender_material_library"]),
    ("Models: check, mend, reduce, transform, export", ["mesh_check", "mesh_fix", "mesh_fix_revert", "mesh_reduce",
                                                        "mesh_transform", "mesh_collision", "mesh_lightmap_uvs", "export_model"]),
    ("Recipes & batches", ["recipe_list", "recipe_save", "recipe_delete", "recipe_apply", "batch_run", "batch_status",
                           "batch_cancel"]),
    ("Retopology", ["retopo_density", "retopo_zone_line", "retopo_zones", "retopo_zone", "retopo_stroke", "retopo_build",
                    "retopo_info", "retopo_view", "retopo_export", "retopo_send_to_blender", "retopo_use_as_model",
                    "retopo_clear", "retopo_patch", "retopo_paint", "retopo_auto_patches", "retopo_fill_gaps",
                    "retopo_flow", "retopo_symmetry", "retopo_rings", "retopo_thin_zones"]),
    ("Patina Assistant", ["mesh_parts", "select_part", "add_tint_layer", "add_material_layer", "update_layer_mask",
                          "uv_island_per_part", "layer_region_faces", "assistant_ask", "assistant_apply",
                          "assistant_check", "assistant_context", "assistant_model", "assistant_panel", "assistant_grammar"]),
]
by = {c["name"]: c for c in cmds}
out = ["# Patina command reference", "",
       "Every command is available as an MCP tool (`patina --mcp`), over TCP as JSON lines",
       "(`{\"id\":1,\"cmd\":\"<name>\",\"args\":{...}}` on 127.0.0.1:7860) and in the in-app Console",
       "(`<name> {json args}`). Generated by `scripts/gen_commands_doc.py` from the live command registry.", "",
       "Tool results that contain images (`render_view`, `render_uv`, `screenshot_window`, `get_texture`,",
       "`get_material` with `preview`) are returned to MCP clients as PNG image content.", "",
       "MCP-only tools: `open_gui_window` — when running headless, opens the desktop window with the",
       "current project and switches all further tools to drive it live; `patina_guide {topic}` — the guides",
       "(workflow, mesh, develop, export, batch, painting, parameters), also MCP resources `patina://guide/<topic>`.",
       "MCP prompts: finish_model, develop_textures, game_ready, batch_folder.", ""]
def num(v):
    return str(int(v)) if isinstance(v, float) and v.is_integer() else str(v)


def write_cmd(n):
    c = by[n]
    out.append("### `%s`\n\n%s\n" % (n, c["description"]))
    props = c["inputSchema"].get("properties", {})
    req = set(c["inputSchema"].get("required", []))
    if not props:
        return
    out.append("| argument | type | range, default | description |\n|---|---|---|---|")
    for k, p in props.items():
        t = " \\| ".join(p["enum"]) if "enum" in p else p.get("type", "")
        rng = []
        if "minimum" in p and "maximum" in p:
            rng.append("%s to %s" % (num(p["minimum"]), num(p["maximum"])))
        if "default" in p:
            rng.append("default %s" % (num(p["default"]) if not isinstance(p["default"], bool) else str(p["default"]).lower()))
        desc = p.get("description", "")
        for k2, p2 in p.get("properties", {}).items():
            r2 = " (%s to %s, default %s)" % (num(p2["minimum"]), num(p2["maximum"]), num(p2.get("default", ""))) \
                if "minimum" in p2 and "maximum" in p2 else ""
            desc += "<br>`%s`%s: %s" % (k2, r2, p2.get("description", ""))
        out.append("| `%s`%s | %s | %s | %s |" % (k, " *(required)*" if k in req else "", t, ", ".join(rng), desc))
    out.append("")


listed = set()
for title, names in groups:
    out.append("## %s\n" % title)
    for n in names:
        if n not in by:
            continue
        listed.add(n)
        write_cmd(n)
rest = [n for n in by if n not in listed and n not in hidden]
if rest:
    out.append("## Other\n")
    for n in rest:
        write_cmd(n)
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "COMMANDS.md")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote %s (%d commands)" % (os.path.normpath(dst), len(cmds)))
